-- The CREATE makes the migration usable on a new database too; Hibernate continues
-- to manage the other tables while the application is transitioned to Flyway.
CREATE TABLE IF NOT EXISTS article (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    description TEXT,
    search TEXT,
    sku VARCHAR(64),
    unit_price NUMERIC(12, 2)
);

ALTER TABLE article ADD COLUMN IF NOT EXISTS sku VARCHAR(64);
ALTER TABLE article ADD COLUMN IF NOT EXISTS unit_price NUMERIC(12, 2);
ALTER TABLE article ADD COLUMN IF NOT EXISTS category VARCHAR(64);
ALTER TABLE article ADD COLUMN IF NOT EXISTS cost_center VARCHAR(128);
ALTER TABLE article ADD COLUMN IF NOT EXISTS unit_of_measure VARCHAR(16);
ALTER TABLE article ADD COLUMN IF NOT EXISTS location VARCHAR(255);
ALTER TABLE article ADD COLUMN IF NOT EXISTS stock_quantity NUMERIC(14, 2);

UPDATE article
SET sku = 'LEGACY-' || id
WHERE sku IS NULL OR BTRIM(sku) = '';

UPDATE article
SET sku = UPPER(REGEXP_REPLACE(BTRIM(sku), '[[:space:]]+', '-', 'g'));

UPDATE article
SET description = CASE
    WHEN description IS NULL OR BTRIM(description) = '' THEN
        COALESCE(NULLIF(REGEXP_REPLACE(BTRIM(name), '[[:space:]]+', ' ', 'g'), ''), 'Articolo ' || id)
    WHEN name IS NULL OR BTRIM(name) = '' THEN
        REGEXP_REPLACE(BTRIM(description), '[[:space:]]+', ' ', 'g')
    WHEN LOWER(REGEXP_REPLACE(BTRIM(name), '[[:space:]]+', ' ', 'g')) =
         LOWER(REGEXP_REPLACE(BTRIM(description), '[[:space:]]+', ' ', 'g')) THEN
        REGEXP_REPLACE(BTRIM(description), '[[:space:]]+', ' ', 'g')
    ELSE
        REGEXP_REPLACE(BTRIM(name), '[[:space:]]+', ' ', 'g') || ' — ' ||
        REGEXP_REPLACE(BTRIM(description), '[[:space:]]+', ' ', 'g')
END;

ALTER TABLE article ALTER COLUMN sku SET NOT NULL;
ALTER TABLE article ALTER COLUMN description SET NOT NULL;
ALTER TABLE article DROP COLUMN IF EXISTS name;

DROP INDEX IF EXISTS uk_article_sku_ci;
CREATE UNIQUE INDEX uk_article_sku_ci ON article (LOWER(sku));

UPDATE article
SET search = REGEXP_REPLACE(BTRIM(CONCAT_WS(' ', sku, description, category,
    cost_center, unit_of_measure, location)), '[[:space:]]+', ' ', 'g');

ALTER TABLE article ALTER COLUMN search SET NOT NULL;
